// Negative control for the emulator's core.
//
// A legitimate guest must never execute an invalid instruction, but a core
// bug (e.g. a wrong decode returning success) would leave it silently running
// with corrupted state. This guest deliberately executes an instruction that
// is reserved on rv64i — the CUSTOM-0 opcode (0b0001011) — and relies on the
// core trapping it (invop_cb) and halting the run with a non-zero status.
//
// Verdict (see makefile / matrix.sh): PASSED iff the emulator process exits
// non-zero here. If main() manages to return, the decode was wrong and the
// harness reports a failure.

#include <stdio.h>

static void illegal_instruction(void) {
    // Reserved CUSTOM-0 opcode: not part of rv64i, never generated by a
    // compliant toolchain, and must not be decodable by the core.
    __asm__ volatile(".word 0x0000000b");
    __asm__ volatile("nop"); // never reached — silences the "no return" path
}

int main(void) {
    printf("TRAP TEST: about to execute an illegal instruction\n");
    fflush(NULL);
    illegal_instruction();
    printf("TRAP TEST BAD: execution continued after an illegal instruction\n");
    return 0;
}
